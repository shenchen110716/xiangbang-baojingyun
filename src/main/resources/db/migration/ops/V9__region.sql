-- 行政区划字典。
--
-- **为什么要有它。**佣金比例按「类目 + 地区」配,而地区是 6 位国标码。
-- 在此之前发单页和配比例页都让人**手填 6 位数字** —— 真用户不知道
-- 320506 是什么,填错了不会报错,只会静默套上另一个地区的比例。
--
-- **一份数据,两端都从这里取。**同一份数据在后端和小程序各存一份的话,
-- 迟早两边不一致 —— 而不一致的表现是"我在小程序上选了苏州,后台却按别处算"。

CREATE TABLE ops.region (
    -- 国标行政区划代码(GB/T 2260)。层级就编码在数字里:
    -- 省 = 前 2 位 + 0000,市 = 前 4 位 + 00,区县 = 完整 6 位
    code        VARCHAR(6) PRIMARY KEY,
    name        VARCHAR(50) NOT NULL,
    -- 省级为 NULL。市级指向省
    parent_code VARCHAR(6),
    -- 1=省 2=市 3=区县。**冗余但值得**:取"某省下面的市"时不用做字符串前缀匹配,
    -- 而前缀匹配在直辖市那里会出错(北京 110000 下面直接是区)
    level       SMALLINT NOT NULL,

    CONSTRAINT region_level_valid CHECK (level BETWEEN 1 AND 3),
    -- 省级没有父级,市/区县必须有 —— 挂空了就选不出来
    CONSTRAINT region_parent_sane CHECK (
        (level = 1 AND parent_code IS NULL) OR (level > 1 AND parent_code IS NOT NULL))
);

CREATE INDEX region_parent_idx ON ops.region (parent_code, code);

