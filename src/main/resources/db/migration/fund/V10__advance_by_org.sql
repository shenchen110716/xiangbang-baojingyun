-- 借支改由**用工单位**审批(老板 2026-08-06:资金/借支/结算属于机构端)。
--
-- 只把权限从平台挪给机构是不够的,那样会造出一个真缺陷:
-- **还款现在是从工人的任意一笔结算里扣的。**甲公司批的借支,
-- 如果工人下一笔工资来自乙公司,就会从乙公司的付款里扣走 ——
-- 甲的钱没出,乙的工人少拿了,而两边都不会报错。
--
-- 所以借支要记住是谁批的,还款只能从那家的结算里扣。

