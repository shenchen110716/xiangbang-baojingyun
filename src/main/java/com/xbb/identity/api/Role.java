package com.xbb.identity.api;

/**
 * 平台级角色(§4.2:身份域负责"账号、实名、鉴权、**授权**")。
 *
 * <p>这里**只放真的被强制执行的角色**。工人/法人代表/经纪人没有列进来,
 * 不是遗漏:那几类判断是"这个人是不是这个组织的法人代表""是不是这单的本人",
 * 属于**归属校验**,依赖具体资源,不是粗粒度角色能表达的。RBAC 叠在它们之上,
 * 不替代它们——两者都要过。
 */
public enum Role {

    /** 能管角色本身:授予/收回。授权链的根。 */
    PLATFORM_ADMIN,

    /** 平台运维:看卡死事件、重放事件这类操作面板。 */
    PLATFORM_OPS
}
